#   저녁(22시 이후): 하루를 마무리하며 돌아보는 주제 (피부 / 바디 / 소소한 일상)
# 각 주제가 주 2회씩 고르게 돌도록 배치. 월~토, 일요일은 쉼.
# ─────────────────────────────────────────────────────────────
SCHEDULE = {
    1: {"morning": 1, "evening": 3},  # 월: 운동 / 얼굴 피부
    2: {"morning": 2, "evening": 5},  # 화: 재테크 / 바디·두피
    3: {"morning": 4, "evening": 6},  # 수: 스트레스·수면 / 소소한 일상
    4: {"morning": 1, "evening": 5},  # 목: 운동 / 바디·두피
    5: {"morning": 2, "evening": 3},  # 금: 재테크 / 얼굴 피부
    6: {"morning": 4, "evening": 6},  # 토: 스트레스·수면 / 소소한 일상
}

# 주제별 '꿀팁형(B)' 확률. 피부·바디·운동은 알려줄 방법이 많아 비중을 높이고,
# 감정이 큰 스트레스/수면·재테크는 고민형(A) 비중을 높인다.
TIP_PROBABILITY = {1: 0.6, 2: 0.35, 3: 0.7, 4: 0.4, 5: 0.7, 6: 0.5}


def current_slot(now: datetime) -> str:
    """KST 기준 오전이면 morning, 오후/밤이면 evening."""
    return "morning" if now.hour < 12 else "evening"

FORMAT_WORRY = (
    "이 글의 형식: (A) 고민 나눔형.\n"
    "[오늘 겪은 고민/장면] → [내가 해본 것·느낀 것] → [사람들에게 슬쩍 던지는 질문]."
    " 마지막은 독자에게 묻는 질문으로 끝내."
)
FORMAT_TIP = (
    "이 글의 형식: (B) 경험 꿀팁 공유형. (질문으로 끝내지 마.)\n"
    "[전에 이 고민이 심했어] → [우연히/유튜브 보고 방법 알게 됨] → "
    "[집에서 따라 할 수 있게 방법을 구체적 단계로] → [며칠 해보니 이만큼 좋아짐, 대략 수치 OK] → "
    "[가볍게 추천하며 마무리]."
    " 방법은 실제로 도움 될 만한 걸로 구체적으로, 브랜드 실명 없이 성분·종류로만 써."
)

# 꿀팁형 마무리 후보 — 매번 다른 걸 골라 'AI 티' 나는 반복을 막는다.
TIP_CLOSERS = [
    "나만 알기 아까워서 적어봄",
    "진짜 별거 아닌데 효과는 쏠쏠했어",
    "혹시 나처럼 고생하면 이거 해봥",
    "믿거나 말거나 난 효과 봤음",
    "지금 고민이면 오늘부터 해보셈",
    "궁금하면 딱 3일만 해봐",
    "안 해봤으면 아까운 거 맞음",
    "나처럼 헤매지 말고 이거부터 해봐",
    "별거 아닌데 이거 알고 좀 편해졌어",
    "속는 셈 치고는 아니고 그냥 한번 해봐",
]


def build_user_message(topic: dict, today: datetime, topic_id: int, slot: str) -> tuple[str, str]:
    """그날·그 시간대의 서브소재·글 형식을 시드로 골라 유저 메시지를 만든다."""
    # 날짜+시간대를 시드로 → 같은 슬롯 재실행 시 동일(중복 방지), 아침/저녁은 서로 다른 글.
    seed = int(today.strftime("%Y%m%d")) * 10 + (0 if slot == "morning" else 1)
    rng = random.Random(seed)
    sub = rng.choice(topic["subs"])
    use_tip = rng.random() < TIP_PROBABILITY.get(topic_id, 0.5)
    fmt = FORMAT_TIP if use_tip else FORMAT_WORRY
    if use_tip:
        closer = rng.choice(TIP_CLOSERS)
        fmt += (
            f"\n이번 글 마무리는 이런 느낌으로: \"{closer}\" "
            "(그대로 베끼지 말고 네 말투로 살짝 바꿔서). "
            "'속는 셈 치고 해봐' 같은 정해진 문구는 쓰지 마."
        )

    user_message = (
        f"오늘의 큰 주제: {topic['name']}\n"
        f"오늘 쓸 구체적 소재: {sub}\n\n"
        f"{fmt}\n\n"
        "위 소재와 형식으로, 오늘 실제로 겪은 일처럼 빵찌의 일상글 한 편을 써줘. "
        "규칙(편한 반말, 담백하게, 구체적 장면 하나, 150~350자, 해시태그 없음, 이모지 0~1개)을 지키고, "
        "의학적 단정·제품 실명·투자 권유는 넣지 말고, 결혼준비·가족 이야기도 넣지 마.\n"
        "말투는 너무 반듯하게 쓰지 말고, 사람들이 자주 쓰는 구어체·가벼운 오타"
        "(해봥, 넘, 걍, 몰겠어, ~함/~됨 같은 명사형 종결 등)를 자연스럽게 섞어줘. "
        "단 'ㅋㅋ'는 쓰지 말고, '왤케'는 억지로 넣지 마.\n"
        "구조가 중요해: [훅 1줄] → 빈 줄 → [본문은 빈 줄 없이 바짝 붙인 짧은 줄들] → "
        "빈 줄 → [마무리 1줄]. 본문 안에서는 줄 사이에 빈 줄을 넣지 마(너무 넓어짐). "
        "글 전체 빈 줄은 2개 정도만."
    )
    return sub, user_message


def generate_post(user_message: str) -> str:
    """Claude로 일상글을 생성한다. (API 키 없으면 예외)"""
    import anthropic

    client = anthropic.Anthropic()  # ANTHROPIC_API_KEY 자동 사용
    response = client.messages.create(
        model=MODEL,
        max_tokens=1024,
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_message}],
    )
    text = next((b.text for b in response.content if b.type == "text"), "").strip()
    if not text:
        sys.exit("[오류] Claude 응답에서 본문 텍스트를 찾지 못했습니다.")
    return text


def post_to_threads(user_id: str, access_token: str, text: str) -> str:
    """Threads 컨테이너 생성 → 30초 대기 → 발행. 게시물 ID 반환."""
    import requests

    create = requests.post(
        f"{THREADS_API}/{user_id}/threads",
        json={"media_type": "TEXT", "text": text, "access_token": access_token},
        timeout=30,
    )
    create.raise_for_status()
    creation_id = create.json()["id"]

    time.sleep(30)  # Threads 권장 대기

    publish = requests.post(
        f"{THREADS_API}/{user_id}/threads_publish",
        json={"creation_id": creation_id, "access_token": access_token},
        timeout=30,
    )
    publish.raise_for_status()
    return publish.json()["id"]


def require_env(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        sys.exit(f"[오류] 환경변수 {name} 가 설정되지 않았습니다.")
    return value


def main() -> None:
    parser = argparse.ArgumentParser(description="빵찌 스레드 자기관리·재테크·피부 일상글 자동 게시")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="게시하지 않고 생성된 글만 출력한다 (검증용).",
    )
    parser.add_argument(
        "--slot",
        choices=["morning", "evening"],
        help="시간대 강제 지정(테스트용). 미지정 시 현재 KST 시각으로 자동 판별.",
    )
    args = parser.parse_args()

    now = datetime.now(KST)
    weekday = now.isoweekday()  # 월=1 ... 일=7
    day_plan = SCHEDULE.get(weekday)
    if day_plan is None:
        print(f"오늘({now:%Y-%m-%d %A})은 게시일이 아닙니다(일요일 쉼). 종료합니다.")
        return

    slot = args.slot or current_slot(now)
    topic_id = day_plan[slot]
    topic = TOPICS[topic_id]

    sub, user_message = build_user_message(topic, now, topic_id, slot)
    slot_label = "아침" if slot == "morning" else "저녁"
    print(f"[{now:%Y-%m-%d %H:%M KST}] {slot_label} / 주제: {topic['name']} / 소재: {sub}")

    # 게시 모드에서만 API 키/토큰을 요구한다. (dry-run은 키만 있으면 됨)
    if not args.dry_run:
        require_env("ANTHROPIC_API_KEY")
        user_id = require_env("THREADS_USER_ID")
        access_token = require_env("THREADS_ACCESS_TOKEN")

    text = generate_post(user_message)
    print("=== 생성된 글 ===")
    print(text)
    print(f"=== 글자 수: {len(text)}자 ===")

    if args.dry_run:
        print("(dry-run) 게시하지 않고 종료합니다.")
        return

    post_id = post_to_threads(user_id, access_token, text)
    print(f"게시 완료. Threads 게시물 ID: {post_id}")


if __name__ == "__main__":
    main()
